"""Export supplied CAD support vertices; no inferred mass/contact calibration."""
import hashlib
import json
import struct
from pathlib import Path
import numpy as np

source=Path(r'C:\Users\arika\Downloads\RW_Walker_Dynamics\rw_dynamics_package\01_CAD\rw_walker_uploaded_assembly.glb')
raw=source.read_bytes();length,_=struct.unpack_from('<II',raw,12)
doc=json.loads(raw[20:20+length]);binary=raw[28+length:]
expected='63be3da5c06b9f198a3d6409b4b0a68ead9c2a638d87f06e7914c40b13693884'
assert hashlib.sha256(raw).hexdigest()==expected, 'Unexpected CAD source; audit before regenerating'
assert len(doc['meshes'])==18
assert all(not any(k in node for k in ['matrix','translation','rotation','scale']) for node in doc['nodes'])
def points(index):
    a=doc['accessors'][doc['meshes'][index]['primitives'][0]['attributes']['POSITION']]
    v=doc['bufferViews'][a['bufferView']]
    assert a['componentType']==5126 and v.get('byteStride',12)==12
    return np.frombuffer(binary,dtype='<f4',offset=v.get('byteOffset',0)+a.get('byteOffset',0),count=a['count']*3).reshape(-1,3).astype(float)
leg=points(0);d=np.linalg.norm(leg[:,1:]-[-17.579,82.825],axis=1)
ring=np.unique(leg[(d>7.98)&(d<8.02),1:],axis=0)
c=np.linalg.lstsq(np.c_[2*ring[:,0],2*ring[:,1],np.ones(len(ring))],np.sum(ring*ring,axis=1),rcond=None)[0]
hip=np.array([0,c[0],c[1]])
lines=['#pragma once','// Generated by tools/generate_cad_support.py; millimetres relative to upper X hinge.',
       '// Supplied GLB SHA256: '+hashlib.sha256(raw).hexdigest(),
       '#include <cstddef>','namespace cad_support {',
       'static constexpr const char* sourceSha256="'+expected+'";',
       'struct Vertex {float x,y,z;};']
for side,index in [('left',7),('right',5)]:
    lines.append('static constexpr Vertex '+side+'[] = {')
    for v in np.unique(points(index)-hip,axis=0):
        lines.append('  {'+','.join(f'{x:.6f}f' for x in v)+'},')
    lines.append('};')
lines.append('}')
dest=Path(__file__).resolve().parents[1]/'src/cad_support_vertices.h'
dest.write_text('\n'.join(lines)+'\n',encoding='utf8')
print(dest)
